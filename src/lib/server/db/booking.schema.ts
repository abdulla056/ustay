/**
 * Booking requests and the message thread (UST-18). Ustay takes booking requests only (decision
 * #3): a guest asks, the owner accepts or declines, nothing is paid online. Guests need only an
 * email (decision #4); `guest_user_id` is the optional account.
 *
 * One table, `booking_request`, holds both kinds: a `booking` (dates, optional room, price
 * snapshot) and a `question` (a general enquiry, no dates and no room). Both share the guest
 * fields and a `booking_message` thread, and the owner's inbox treats them as one list.
 *
 * - `room_id` is a composite FK `(property_id, room_id)` -> `room(property_id, id)`: the room must
 *   belong to the same property. The migration hand-edits the action to
 *   `ON DELETE SET NULL (room_id)` (Postgres 15+) so deleting the room clears only `room_id` and
 *   never nulls `property_id`. Drizzle cannot express the column list and the snapshot records a
 *   plain `set null`.
 * - `check_in` / `check_out` are calendar dates in the property's timezone, not instants.
 * - The price is a snapshot taken at creation (`nightly_rate_minor`, `estimated_total_minor`, in
 *   the property's currency, integer minor units), so a later rate change never rewrites what the
 *   guest was shown.
 * - `guest_access_token_hash` is the SHA-256 hex of a random token that is emailed to the guest
 *   once. The plain token is never stored.
 *
 * Conventions: `docs/DATABASE.md`. Relations live in `./relations`.
 */
import { sql } from 'drizzle-orm';
import {
	check,
	date,
	foreignKey,
	index,
	integer,
	pgEnum,
	pgTable,
	text,
	timestamp
} from 'drizzle-orm/pg-core';
import { id, timestamps, userRef, uuidRef } from './helpers';
import { property } from './property.schema';
import { room } from './room.schema';

export const bookingRequestKinds = ['booking', 'question'] as const;
export const bookingRequestKind = pgEnum('booking_request_kind', bookingRequestKinds);

export const bookingRequestStatuses = [
	'pending',
	'accepted',
	'declined',
	'cancelled',
	'expired',
	'closed'
] as const;
export const bookingRequestStatus = pgEnum('booking_request_status', bookingRequestStatuses);

export const bookingMessageSenders = ['guest', 'host', 'system'] as const;
export const bookingMessageSender = pgEnum('booking_message_sender', bookingMessageSenders);

export const bookingRequest = pgTable(
	'booking_request',
	{
		id: id(),
		propertyId: uuidRef('property_id')
			.notNull()
			.references(() => property.id, { onDelete: 'cascade' }),
		/** Short human code such as `UST-7K3P9Q`, generated by the repo. */
		reference: text('reference').notNull().unique(),
		kind: bookingRequestKind('kind').notNull(),
		/** Nullable; cleared (not the request) when the room is deleted. See the file header. */
		roomId: uuidRef('room_id'),
		checkIn: date('check_in', { mode: 'string' }),
		checkOut: date('check_out', { mode: 'string' }),
		adults: integer('adults'),
		children: integer('children'),
		guestName: text('guest_name').notNull(),
		/** Trimmed and lower-cased by the repo; the CHECK enforces lower case and an `@`. */
		guestEmail: text('guest_email').notNull(),
		guestPhone: text('guest_phone'),
		guestUserId: userRef('guest_user_id', 'set null'),
		/** The guest's opening note (also written as the first `guest` message). */
		message: text('message'),
		status: bookingRequestStatus('status').notNull().default('pending'),
		respondedAt: timestamp('responded_at', { withTimezone: true }),
		cancelledAt: timestamp('cancelled_at', { withTimezone: true }),
		/** Created + 72 hours, set by the repo (`REQUEST_TTL_MS`). */
		expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
		/** Copied from the property at creation. */
		currency: text('currency').notNull(),
		/** Minor units in `currency`; the room's rate at creation. */
		nightlyRateMinor: integer('nightly_rate_minor'),
		/** `nightly_rate_minor` x nights, exact, no rounding. */
		estimatedTotalMinor: integer('estimated_total_minor'),
		/** SHA-256 hex of the guest access token. The plain token is never stored. */
		guestAccessTokenHash: text('guest_access_token_hash').notNull().unique(),
		...timestamps()
	},
	(t) => [
		foreignKey({
			name: 'booking_request_room_fk',
			columns: [t.propertyId, t.roomId],
			foreignColumns: [room.propertyId, room.id]
		}).onDelete('set null'),
		// A CHECK passes on NULL, so every required column is spelled out with IS NOT NULL.
		check(
			'booking_request_kind_check',
			sql`(
				${t.kind} = 'booking'
				AND ${t.checkIn} IS NOT NULL AND ${t.checkOut} IS NOT NULL
				AND ${t.checkOut} > ${t.checkIn}
				AND ${t.adults} IS NOT NULL AND ${t.adults} >= 1
				AND ${t.children} IS NOT NULL AND ${t.children} >= 0
			) OR (
				${t.kind} = 'question'
				AND ${t.checkIn} IS NULL AND ${t.checkOut} IS NULL
				AND ${t.roomId} IS NULL
				AND ${t.adults} IS NULL AND ${t.children} IS NULL
				AND ${t.nightlyRateMinor} IS NULL AND ${t.estimatedTotalMinor} IS NULL
			)`
		),
		// A question is only ever pending or closed; a booking is never closed.
		check(
			'booking_request_status_check',
			sql`(${t.kind} = 'booking' AND ${t.status} <> 'closed')
				OR (${t.kind} = 'question' AND ${t.status} IN ('pending', 'closed'))`
		),
		check('booking_request_guest_name_check', sql`${t.guestName} ~ '\\S'`),
		check(
			'booking_request_guest_email_check',
			sql`${t.guestEmail} = lower(${t.guestEmail}) AND ${t.guestEmail} LIKE '%@%'`
		),
		check('booking_request_message_check', sql`${t.message} ~ '\\S'`),
		check('booking_request_currency_check', sql`${t.currency} ~ '^[A-Z]{3}$'`),
		check(
			'booking_request_price_check',
			sql`(${t.nightlyRateMinor} IS NULL) = (${t.estimatedTotalMinor} IS NULL)
				AND ${t.nightlyRateMinor} >= 0 AND ${t.estimatedTotalMinor} >= 0`
		),
		index('booking_request_property_id_status_created_at_idx').on(
			t.propertyId,
			t.status,
			t.createdAt.desc()
		),
		index('booking_request_guest_email_idx').on(t.guestEmail),
		index('booking_request_guest_user_id_idx').on(t.guestUserId),
		index('booking_request_expires_at_pending_idx')
			.on(t.expiresAt)
			.where(sql`${t.status} = 'pending'`)
	]
);

/** Append-only: messages are never updated or edited. */
export const bookingMessage = pgTable(
	'booking_message',
	{
		id: id(),
		bookingRequestId: uuidRef('booking_request_id')
			.notNull()
			.references(() => bookingRequest.id, { onDelete: 'cascade' }),
		sender: bookingMessageSender('sender').notNull(),
		/** Null for a guest without an account, and for `system` messages. */
		authorUserId: userRef('author_user_id', 'set null'),
		body: text('body').notNull(),
		createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull()
	},
	(t) => [
		check('booking_message_body_check', sql`${t.body} ~ '\\S'`),
		index('booking_message_booking_request_id_created_at_idx').on(t.bookingRequestId, t.createdAt)
	]
);
